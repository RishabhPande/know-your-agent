"""Seeded transaction corpus for evaluating the KYA gate (v1).

The gate in credentials.py, delegation.py, and policy.py is only as
convincing as the traffic it has been run against. This module builds
that traffic: a labeled, fully synthetic corpus of agent purchase
transactions at the credential layer, generated deterministically from
a seed so any result reported over it can be regenerated byte for byte.

The corpus has three families of classes:

- Legitimate traffic: valid single credentials and valid delegation
  chains presenting in-scope purchases inside their session windows.
- Policy violations by valid agents: the credential verifies, but the
  purchase asks for more than the scope allows (over the amount limit,
  a category outside the scope). These are the benchmark module's
  ambiguous class: a legitimate agent overstepping, not a fraudster.
  Their label is None.
- Attacks: forged signatures, tampered payload fields, expired and
  not-yet-valid credentials, revoked-credential reuse, replay, and
  delegation-chain attacks (widened scope, widened window, broken
  linkage, principal mismatch, mid-chain revocation), plus malformed
  presentations. Their label is 1.

One class is deliberately uncomfortable: ``replay_in_window`` replays a
genuine presentation while the credential is still inside its session
window and the purchase is still in scope. KYA v0.1 has no nonce or
idempotency token, so the gate accepts these. The class exists so the
limitation is measured and reported, not discovered by a reviewer.

Determinism: keys are derived from the seed (SHA-256 into Ed25519
private bytes), credential ids come from a counter, all randomness
flows through one ``random.Random(seed)``, and issuance runs under a
fixed clock so ``issued_at`` does not leak wall time into the output.
Building the same corpus twice with the same seed produces identical
JSON. Attack constructions that need a signed but rule-breaking chain
link (a widened scope, a foreign principal) are issued directly with
``issue_credential``, bypassing ``delegate_credential``'s checks, on
purpose: they model a rogue or buggy delegating service whose output
``verify_chain`` exists to catch.

This module is deliberately independent of kya.agentrisk: the corpus
is generated at the credential layer and shares no data, taxonomy, or
results with any agent-behavior simulation.
"""

